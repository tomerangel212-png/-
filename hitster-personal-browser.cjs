"use strict";
const assert=require("node:assert/strict"),fs=require("node:fs"),path=require("node:path"),http=require("node:http");
const {chromium}=require("playwright");
const songs=[["לו יהי","נעמי שמר"],["Take on Me","a-ha"],["כוח הכבידה","שגיב ברייטנר"],["כולם גנבים","אושר כהן"],["One Last Time","Ariana Grande"]];
const fixtures=songs.map(([trackName,artistName],i)=>({trackId:100+i,trackName,artistName,releaseDate:"2014-01-01",previewUrl:"https://media.example.test/"+i+".m4a"}));
const mime={".html":"text/html",".js":"application/javascript",".json":"application/json"};
const server=http.createServer((req,res)=>{
  const file=path.join(process.cwd(),decodeURIComponent(new URL(req.url,"http://localhost").pathname));
  if(!file.startsWith(process.cwd()+path.sep)){res.writeHead(403);res.end();return;}
  fs.readFile(file,(error,data)=>{res.writeHead(error?404:200,{"Content-Type":mime[path.extname(file)]||"text/plain"});res.end(error?"missing":data);});
});
(async()=>{
  await new Promise(r=>server.listen(0,"127.0.0.1",r));
  const browser=await chromium.launch({headless:true}),page=await browser.newPage({viewport:{width:390,height:844}});
  const errors=[];page.on("pageerror",e=>errors.push(e.message));
  await page.route("**/hitster-world-data.json*",route=>route.fulfill({json:{retrievedAt:"2026-10-04T12:00:00Z",countries:{il:{source:"https://rss.marketingtools.apple.com/api/v2/il/music/most-played/10/songs.json",tracks:[{id:"100"}]}},seeds:[]}}));
  await page.route("**/itunes.apple.com/**",route=>{
    const url=new URL(route.request().url()),callback=url.searchParams.get("callback"),term=url.searchParams.get("term")||"";
    const results=term?fixtures.filter(t=>term.includes(t.trackName)):fixtures;
    route.fulfill({contentType:callback?"application/javascript":"application/json",body:callback?callback+"("+JSON.stringify({results})+")":JSON.stringify({results})});
  });
  await page.route("**/media.example.test/**",route=>route.abort());
  await page.goto("http://127.0.0.1:"+server.address().port+"/hitster-personal.html");
  assert.equal(await page.locator("#setup-modal").isVisible(),true);
  assert.equal(await page.locator("#song-0").count(),1);
  assert.equal(await page.locator("#five-rows fieldset").count(),5);
  assert.equal(await page.evaluate(()=>document.querySelector("#game-main").inert),true);
  await page.locator("#song-4").fill("Take on Me");
  await page.locator("#start-personal").click();
  await page.waitForFunction(()=>document.querySelector("#setup-error").textContent.includes("שונים"));
  assert.equal(await page.locator("#setup-modal").isVisible(),true);
  await page.locator("#song-4").fill("One Last Time");
  await page.locator(".personal-options summary").click();
  await page.locator("#spotify-url").fill("https://open.spotify.com/playlist/test");
  await page.locator("#start-personal").click();
  await page.waitForFunction(()=>document.querySelector("#setup-modal").hidden);
  await page.waitForFunction(()=>document.querySelectorAll("#teams .team").length===5);
  assert.equal(await page.locator(".team-lives").count(),5);
  assert.ok((await page.locator(".team-lives").allTextContents()).every(text=>text.includes("10/10")));
  await page.locator("#lose-life-team-1").click();
  assert.ok((await page.locator(".team-lives").first().innerText()).includes("9/10"));
  assert.ok((await page.locator(".team-lives").nth(1).innerText()).includes("10/10"));
  assert.ok((await page.locator("#personal-note").innerText()).includes("5 גרסאות"));
  assert.equal(await page.locator("#start-screen").isVisible(),false,"No second startup popup");
  assert.equal(await page.locator("#spotify-saved").getAttribute("href"),"https://open.spotify.com/playlist/test");
  await page.locator("#manager-panel summary").click();
  await page.locator("#reward-listening").click();
  assert.ok((await page.locator("#listening-scores").innerText()).includes("תומר: 1"));
  await page.locator("#manager-team").selectOption("team-2");
  await page.locator("#penalize-noise").click();
  assert.ok((await page.locator("#listening-scores").innerText()).includes("קבוצה 2: -1"));
  await page.locator("#undo-score").click();
  assert.ok((await page.locator("#listening-scores").innerText()).includes("קבוצה 2: 0"));
  await page.locator("#learning-panel summary").click();
  for(let i=0;i<8;i++) await page.locator("#next-lesson").click();
  assert.ok((await page.locator("#lesson-title").innerText()).includes("לא מאומת"));
  await page.locator("#next-lesson").click();
  assert.ok((await page.locator("#lesson-title").innerText()).includes("יצירתי"));
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),true,"Mobile width");
  await page.screenshot({path:"hitster-personal-mobile.png",fullPage:true});
  assert.deepEqual(errors,[]);
  await browser.close();server.close();
  console.log("Browser checks passed: five-song gate, duplicate rejection, one popup, matched recordings, saved provider link, manager score/undo, learning labels, mobile width.");
})().catch(error=>{console.error(error);server.close();process.exit(1);});
